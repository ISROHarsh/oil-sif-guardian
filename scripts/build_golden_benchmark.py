def build_golden_benchmark():
    all_raw = BENCHMARK_SCENARIOS + ADDITIONAL_CATEGORIES
    records = []

    for idx, sc in enumerate(all_raw):
        b_id = f"BM-{idx+1:03d}"
        
        # Format evidence spans to character offsets within the narrative
        narrative = sc["narrative"]
        formatted_spans = []
        for s in sc.get("spans", []):
            span_text = s["text"]
            cat = s.get("category", "HAZARD")
            start = narrative.find(span_text)
            if start != -1:
                end = start + len(span_text)
                formatted_spans.append({
                    "text": span_text,
                    "start_char": start,
                    "end_char": end,
                    "category": cat
                })

        records.append({
            "benchmark_id": b_id,
            "title": sc["title"],
            "site": sc["site"],
            "location": sc.get("location", "Operational Area"),
            "activity": sc.get("activity", "Maintenance"),
            "narrative": narrative,
            "ground_truth": {
                "is_psif": sc["is_psif"],
                "psif_priority": sc["psif_priority"],
                "primary_iogp_rule": sc.get("primary_iogp_rule"),
                "secondary_iogp_rules": sc.get("secondary_iogp_rules", []),
                "entities": {
                    "hazards": sc.get("hazards", []),
                    "energy_sources": sc.get("energy_sources", []),
                    "controls": sc.get("controls", []),
                    "control_failures": sc.get("control_failures", [])
                },
                "evidence_spans": formatted_spans,
                "adjudication_rationale": sc.get("rationale", "Expert HSE Adjudication Consensus.")
            }
        })

    out_dir = Path(__file__).resolve().parents[1] / "data" / "evaluation"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_file = out_dir / "golden_benchmark.json"

    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(records, f, indent=2)

    print(f"Successfully generated {len(records)} golden benchmark records at {out_file}")
    return records


if __name__ == "__main__":
    build_golden_benchmark()
